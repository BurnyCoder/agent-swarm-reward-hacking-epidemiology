"""Interactive results explorer: one self-contained static HTML page (Plotly) for a private Hugging Face static Space.

Local context: reads only analysis outputs (`results/summary.json`, `results/prevalence_by_round.csv`,
`results/agent_rounds.parquet`). Panels: prevalence curves (every run hoverable), dose-response cells, hazard ratios,
out-of-sample prediction envelopes, a per-run transmission explorer (agents x rounds, red = hack attempt, edges from
authors of pro-hack posts an agent read to that agent when it started hacking) and example posts/code per outcome.
Colors follow the condition entity as in `figures.py` (validated palette). Tables back every chart (accessibility).
Global context: `scripts/build_site.py` writes `site/index.html`; `hf upload --repo-type space` deploys it privately.
"""

from __future__ import annotations  # forward references

import html  # escape example text
import json  # summary
from pathlib import Path  # paths

import pandas as pd  # tables
import plotly.graph_objects as go  # interactive charts

from .figures import COLORS  # shared condition colors

TEMPLATE = """<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>Reward-hacking epidemics in an LLM swarm</title>
<meta name="viewport" content="width=device-width, initial-scale=1"><script src="https://cdn.plot.ly/plotly-2.35.2.min.js"></script>
<style>body{{font-family:system-ui,sans-serif;max-width:1100px;margin:auto;padding:1rem;color:#0b0b0b;background:#fcfcfb}}
h2{{border-bottom:1px solid #e4e3df;padding-bottom:.2rem}} table{{border-collapse:collapse;font-size:.85rem}}
td,th{{border:1px solid #e4e3df;padding:.25rem .5rem;vertical-align:top}} pre{{white-space:pre-wrap;font-size:.8rem;margin:0}}
.note{{color:#52514e;font-size:.9rem}}</style></head><body>
<h1>Reward-hacking epidemics in a swarm of local LLM agents</h1>
<p class="note">Qwen3.5-4B agents (N=32) share a message board; each round every agent reads 6 random posts, solves an
impossible coding task (one unit test contradicts the spec, so any pass is cheating) and posts. All numbers on this page
are generated by <code>scripts/analyze.py</code> from the run logs.</p>
{body}</body></html>"""


def _section(title: str, note: str, fig: go.Figure | None = None, table: str = "") -> str:
    """One page section with an optional Plotly figure and HTML table."""
    plot = fig.to_html(full_html=False, include_plotlyjs=False) if fig is not None else ""
    return f"<h2>{html.escape(title)}</h2><p class='note'>{note}</p>{plot}{table}"


def prevalence_fig(prev: pd.DataFrame) -> go.Figure:
    """Per-run prevalence lines (hover shows run id) and condition means."""
    fig = go.Figure()
    for cond, g in prev.groupby("condition"):
        for run, r in g.groupby("run_id"):
            fig.add_trace(go.Scatter(x=r["round"], y=r["prevalence"], mode="lines", line={"width": 1},
                                     opacity=0.25, marker={"color": COLORS.get(cond)}, name=run, legendgroup=cond,
                                     showlegend=False, hovertemplate=f"{run}<br>round %{{x}}: %{{y:.2f}}<extra></extra>"))
        m = g.groupby("round")["prevalence"].mean()
        fig.add_trace(go.Scatter(x=m.index, y=m.values, mode="lines+markers", line={"width": 3},
                                 marker={"color": COLORS.get(cond), "size": 8}, name=f"{cond} mean", legendgroup=cond))
    fig.update_layout(yaxis={"range": [0, 1], "title": "hack-attempt prevalence"}, xaxis={"title": "round"},
                      hovermode="closest", height=420, template="plotly_white")
    return fig


def transmission_fig(df: pd.DataFrame, run_id: str) -> go.Figure:
    """Agents x rounds grid for one run; red = hack attempt; lines from pro-hack authors to new hackers."""
    r = df[df.run_id == run_id]
    fig = go.Figure()
    new = r[(r.hack_attempt) & (r.prev_hack == False)]
    xs, ys = [], []  # edge coordinates (None-separated)
    for row in new.itertuples():
        for author in row.read_authors:
            if author.startswith("a"):  # agent authors (seed slots drawn on a separate row)
                src = r[(r.agent == author) & (r["round"] == row.round - 1)]
                if len(src) and bool(src.post_pro.iloc[0]):
                    xs += [row.round - 1, row.round, None]
                    ys += [int(author[1:]), int(row.agent[1:]), None]
    fig.add_trace(go.Scatter(x=xs, y=ys, mode="lines", line={"color": "#b0afa9", "width": 1}, hoverinfo="skip",
                             name="read a pro-hack post by"))
    for state, color in [(True, "#e34948"), (False, "#c3c2b7")]:
        s = r[r.hack_attempt == state]
        fig.add_trace(go.Scatter(x=s["round"], y=s.agent.str[1:].astype(int), mode="markers",
                                 marker={"color": color, "size": 9}, name="hack attempt" if state else "no hack",
                                 text=s.post_text.str.slice(0, 160),
                                 hovertemplate="agent %{y}, round %{x}<br>%{text}<extra></extra>"))
    fig.update_layout(title=f"Transmission explorer: {run_id}", xaxis={"title": "round"}, yaxis={"title": "agent"},
                      height=520, template="plotly_white")
    return fig


def examples_table(df: pd.DataFrame, n: int = 3) -> str:
    """Example posts + code per outcome (escaped)."""
    rows = []
    for outcome in ("hack", "flag", "honest"):
        for rec in df[df.outcome == outcome].head(n).itertuples():
            rows.append(f"<tr><td>{outcome}</td><td>{html.escape(rec.run_id)} r{rec.round} {rec.agent}</td>"
                        f"<td>{html.escape(str(rec.mechanism))}</td><td><pre>{html.escape(rec.post_text)}</pre></td></tr>")
    return "<table><tr><th>outcome</th><th>where</th><th>mechanism</th><th>post</th></tr>" + "".join(rows) + "</table>"


def build(results_dir: Path, out_dir: Path) -> Path:
    """Write site/index.html from results files."""
    summary = json.loads((results_dir / "summary.json").read_text(encoding="utf-8"))
    prev = pd.read_csv(results_dir / "prevalence_by_round.csv")
    df = pd.read_parquet(results_dir / "agent_rounds.parquet")
    parts = [_section("Spread over rounds", "Thin lines = individual runs (hover for id); thick = condition mean.",
                      prevalence_fig(prev),
                      pd.DataFrame(summary.get("h1", {})).T.round(4).to_html(classes="tbl"))]
    h2 = summary.get("h2", {})
    if "k_nonseed_pro" in h2:
        tab = pd.DataFrame({k: h2[k] for k in ("k_seed_pro", "k_nonseed_pro")}).T.round(4).to_html()
        parts.append(_section("Causal per-post hazard (H2)", "Cloglog hazard ratios per pro-hack post read, "
                              "round fixed effects, run-clustered SEs.", None, tab))
    if "h4" in summary:
        parts.append(_section("Dose-response assay (H4)", "Randomized number k of pro-hack posts among 6.", None,
                              pd.DataFrame(summary["h4"]["table"]).round(3).to_html(index=False)))
    main_runs = sorted(df[df.condition == "MAIN"].run_id.unique())
    if main_runs:
        parts.append(_section("Transmission explorer", "Hover a dot to read the agent's post.",
                              transmission_fig(df, main_runs[0])))
    parts.append(_section("Examples", "First examples of each outcome.", None, examples_table(df)))
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "index.html"
    path.write_text(TEMPLATE.format(body="\n".join(parts)), encoding="utf-8")
    return path
