"""Render experiment reports from templates so every number in them comes from a results file.

Usage: uv run python scripts/make_reports.py   -> reports/experiments/<name>.md for every reports/templates/<name>.md
Local context: each template is Markdown with Python format fields such as `{smoke_v1[solve][n]}` or
`{length_probe[D][share_le_768]:.1%}`. Every JSON file under results/ (recursively) and data/ is loaded under its file
stem (e.g. results/engineering/length_probe.json -> `length_probe`) and under `<folder>_<stem>` (e.g.
results/explore/summary.json -> `explore_summary`), and `str.format_map` fills the fields
(https://docs.python.org/3/library/string.html#format-string-syntax: `[key]` indexes a mapping with a string key).
A template whose input FILE does not exist yet is skipped with a message; a value missing inside an existing file
renders as "n/a". The command can be rerun at any stage.
Global context: `scripts/analyze.py` regenerates results/; this script then regenerates the reports (one command each).
"""

from __future__ import annotations  # forward references

import json  # results files
from pathlib import Path  # paths

ROOT = Path(__file__).resolve().parents[1]  # repo root
TEMPLATES, OUT = ROOT / "reports" / "templates", ROOT / "reports" / "experiments"


class _Missing:
    """Placeholder for a value absent inside an existing results file (e.g. H2 reported "too few events"): any
    further [key] returns itself and any format spec renders "n/a", so one missing number does not drop a report."""

    def __getitem__(self, key):
        return self

    def __format__(self, spec: str) -> str:
        return "n/a"

    __str__ = __repr__ = lambda self: "n/a"


MISSING = _Missing()


class _SafeDict(dict):
    def __missing__(self, key):  # str.format's [key] lookup lands here for absent keys
        if isinstance(key, int) and str(key) in self:  # format turns "[0]" into int 0; JSON keys are strings
            return self[str(key)]
        return MISSING


class _SafeList(list):
    def __getitem__(self, i):
        try:
            return super().__getitem__(i)
        except (IndexError, TypeError):
            return MISSING


def _safe(x):
    """Recursively wrap parsed JSON so absent nested keys/indices render as n/a."""
    if isinstance(x, dict):
        return _SafeDict({k: _safe(v) for k, v in x.items()})
    if isinstance(x, list):
        return _SafeList(_safe(v) for v in x)
    return x


def load_namespace() -> dict:
    """{file stem: parsed JSON} for every JSON file in results/ and data/ (later directories win on name clashes)."""
    ns = {}
    for base in (ROOT / "data", ROOT / "results"):
        for p in sorted(base.rglob("*.json")) if base.exists() else []:
            d = _safe(json.loads(p.read_text(encoding="utf-8")))  # nested gaps render as n/a
            ns[p.stem] = d  # short key, e.g. `length_probe`
            ns[f"{p.parent.name}_{p.stem}"] = d  # folder-qualified key, e.g. `explore_summary` vs `results_summary`
    return ns


def main() -> None:
    ns = load_namespace()
    OUT.mkdir(parents=True, exist_ok=True)
    for t in sorted(TEMPLATES.glob("*.md")):
        try:
            text = t.read_text(encoding="utf-8").format_map(ns)  # fill every {field} from results files
        except KeyError as e:  # an input of this report does not exist yet
            print(f"skip {t.name}: missing {e}")
            continue
        if t.name == "README_results.md":  # results block inside README.md, between the marker comments
            readme = ROOT / "README.md"
            body = readme.read_text(encoding="utf-8")
            start, end = body.index("<!-- results:start"), body.index("<!-- results:end -->")
            start = body.index("\n", start) + 1  # keep the start-marker line
            readme.write_text(body[:start] + text.strip() + "\n" + body[end:], encoding="utf-8", newline="\n")
            print("wrote README.md results block")
            continue
        header =f"<!-- generated by scripts/make_reports.py from reports/templates/{t.name}; do not edit -->\n"
        dest = OUT.parent if t.name == "summary.md" else OUT  # the all-experiments summary lives in reports/
        (dest / t.name).write_text(header + text, encoding="utf-8", newline="\n")
        print(f"wrote {dest.relative_to(ROOT).as_posix()}/{t.name}")


if __name__ == "__main__":
    main()
