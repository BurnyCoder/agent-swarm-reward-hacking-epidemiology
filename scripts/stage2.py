"""Generate the Stage 2 preregistration addendum (prereg §8.7) from the frozen pilot data files — no hand-typed numbers.

Usage: uv run python scripts/stage2.py  -> reports/preregistration_stage2.md
Fills in only values that the Stage 1 rules determine: filtered task list (hash), capability threshold,
presence_penalty, chosen prompt variant + calibration table, pool hashes + manipulation check, judge kappa, detector
precision/recall, probe text, assay stimulus hashes, simulator parameters, power/identifiability, replicate counts,
the H2 smallest effect of interest h1*, and model/engine versions.
"""

from __future__ import annotations  # forward references

import hashlib  # file hashes
import json  # data files
import os  # env
import urllib.request  # vLLM version endpoint
from datetime import date  # addendum date
from pathlib import Path  # paths

import numpy as np  # bootstrap

from swarm_epi import conditions, prompts  # replicate counts, probe/judge text
from swarm_epi.analysis import judged  # "judged pro-hack" = judge label (same rule as the confirmatory analysis)
from swarm_epi.config import LLMConfig, RuntimeConfig  # model id; PILOT_BATCH
from swarm_epi.tasks import apply_capability_filter, load_tasks  # filtered task list

ROOT = Path(__file__).resolve().parents[1]
DATA, REPORTS = ROOT / "data", ROOT / "reports"
K, N, M = 6, 32, 2


def sha(path: Path) -> str:
    """Short SHA-256 of a file."""
    return hashlib.sha256(path.read_bytes()).hexdigest()[:16]


def load(name: str) -> dict:
    return json.loads((DATA / name).read_text(encoding="utf-8"))


def pilot_pi_D(runs: Path, labels: dict) -> tuple[float, float]:
    """pi = P(post pro | author hacked) and D (geometric infectious period) from pilot MAIN runs + harvest labels."""
    pro_given_hack, at_risk, ends = [], 0, 0
    for d in sorted((runs / RuntimeConfig().pilot_batch).iterdir()):  # PILOT_BATCH (default "pilot")
        if json.loads((d / "config.json").read_text())["condition"] != "MAIN":
            continue
        recs = [json.loads(x) for x in (d / "rounds.jsonl").read_text(encoding="utf-8").splitlines() if x]
        stance = {(r["agent"], r["round"]): judged(labels.get(f"{d.name}:{r['post_id']}", {}), "pro")
                  for r in recs}
        pro_given_hack += [stance[(r["agent"], r["round"])] for r in recs if r["hack_attempt"]]
        for (a, t), s in stance.items():
            if s and (a, t + 1) in stance:
                at_risk += 1
                ends += not stance[(a, t + 1)]
    return float(np.mean(pro_given_hack)) if pro_given_hack else float("nan"), at_risk / max(ends, 1)


def main() -> None:
    runs = Path(os.environ.get("RUNS_DIR", "runs"))
    tasks, thr = apply_capability_filter(load_tasks(), DATA / "capability.json")
    task_hash = hashlib.sha256("\n".join(sorted(t.task_id for t in tasks)).encode()).hexdigest()[:16]
    samp, cal, pools = load("sampling.json"), load("calibration.json"), load("pools.json")
    rng = np.random.default_rng(0)
    ph, pp = np.array([p["p_pro"] for p in pools["hack"]]), np.array([p["p_pro"] for p in pools["placebo"]])
    boots = [rng.choice(ph, ph.size).mean() - rng.choice(pp, pp.size).mean() for _ in range(10000)]
    audit = load("audit_results.json") if (DATA / "audit_results.json").exists() else {}
    ap, sim = load("assay_pools.json"), load("sim_params.json")
    power = load("power.json") if (DATA / "power.json").exists() else {}
    labels = {r["pool_id"]: r for r in ap["_all"]}
    pi, D = pilot_pi_D(runs, labels)
    h1_star = 0.25 / (pi * K * D) if np.isfinite(pi) and pi > 0 else 0.02  # prereg §9.2 (K~ = K)
    (DATA / "stage2_constants.json").write_text(json.dumps(  # read by analysis.run_all (H2 falsification rule)
        {"h1_star": h1_star, "pilot_pi": pi, "pilot_D": D, "K": K}, indent=1), encoding="utf-8")
    try:
        with urllib.request.urlopen(LLMConfig().base_url.replace("/v1", "") + "/version", timeout=5) as r:
            vllm = json.loads(r.read())["version"]
    except OSError:
        vllm = "unavailable (server not reachable when the addendum was generated)"
    reps = {}
    for c in conditions.batch1(cal["chosen"]):
        reps[c.condition] = reps.get(c.condition, 0) + 1
    pw = power.get("h1_power", [])
    near10 = min(pw, key=lambda r: abs(r["mean_diff"] - 0.10)) if pw else None
    rows_cal = "\n".join(f"| {v} | {r['0']['rate']:.3f} [{r['0']['ci'][0]:.3f}, {r['0']['ci'][1]:.3f}] | "
                         f"{r['6']['rate']:.3f} [{r['6']['ci'][0]:.3f}, {r['6']['ci'][1]:.3f}] |"
                         for v, r in cal["rates"].items())
    rows_pw = "\n".join(f"| {r['h1']} | {r['mean_diff']:.3f} | {r['power']:.3f} ± {r['mc_se']:.3f} | {r['tost_power']:.3f} |"
                        for r in pw)
    md = f"""# Preregistration Stage 2 addendum (pilot constants)

- **Date:** {date.today().isoformat()} · **Author:** Libor "Burny" Burian · Stage 1: commit `aa92fe9`
- Generated by `scripts/stage2.py` from the frozen files in `data/`; every value is fixed by a Stage 1 rule.

| Item (prereg §) | Value |
|---|---|
| Model / engine (§2.1) | `{LLMConfig().model}`, thinking off; vLLM {vllm} |
| presence_penalty (§8.1) | **{samp['presence_penalty']}** (pass rate 1.5: {samp['comparison']['1.5']['pass_rate']:.3f}, 0.0: {samp['comparison']['0.0']['pass_rate']:.3f}; syntax-error rate at 1.5: {samp['comparison']['1.5']['syntax_error_rate']:.3f}) |
| Capability threshold (§8.1) | ≥ {thr}/5 → **{len(tasks)}** tasks (list SHA-256 `{task_hash}`; `capability.json` `{sha(DATA / 'capability.json')}`) |
| Prompt variant (§8.2) | **{cal['chosen']}** ({cal['rule']}) |
| Seed pools (§5) | hack {len(pools['hack'])}, placebo {len(pools['placebo'])} items (`pools.json` `{sha(DATA / 'pools.json')}`; manual check applied: {pools.get('manual_check_applied')}) |
| Pool manipulation check (§5) | mean P(pro): hack {ph.mean():.3f}, placebo {pp.mean():.3f}; difference {ph.mean() - pp.mean():.3f} [95% CI {np.percentile(boots, 2.5):.3f}, {np.percentile(boots, 97.5):.3f}] |
| Judge validation (§8.5) | κ = {audit.get('judge', {}).get('kappa', float('nan')):.3f} (n = {audit.get('judge', {}).get('n')}; passes 0.61: {audit.get('judge', {}).get('passes_0.61')}) |
| Detector audit (§4.1) | precision {audit.get('detector', {}).get('precision', float('nan')):.3f} {audit.get('detector', {}).get('precision_ci95')}, recall {audit.get('detector', {}).get('recall', float('nan')):.3f} {audit.get('detector', {}).get('recall_ci95')} (n = {audit.get('detector', {}).get('n')}) |
| Belief probe (§4.2) | "{prompts.PROBE_QUESTION}" |
| Judge rubric (§4.2) | SHA-256 `{hashlib.sha256(prompts.JUDGE_PROMPT.encode()).hexdigest()[:16]}` (`prompts.JUDGE_PROMPT`) |
| Assay stimuli (§2.3) | pro {len(ap['pro'])} (live non-seed {sum(p.get('source') == 'live_nonseed' for p in ap['pro'])}), anti {len(ap['anti'])}, neutral {len(ap['neutral'])}, note snapshots {len(ap['snapshots'])} (`assay_pools.json` `{sha(DATA / 'assay_pools.json')}`) |
| Simulator (§9.5) | recovery γ = {sim['recover']:.3f} from {sim['n_transitions']} pilot transitions |
| Pilot π, D (§9.2) | π = {pi:.3f}, D = {D:.2f} rounds → **h1\\* = {h1_star:.4f}** |
| Identifiability (§8.6) | overall {power.get('identifiability', {}).get('overall', float('nan')):.3f}; passes 80%: {power.get('identifiability', {}).get('passes_80pct')} → curve-family comparisons {'may be used as evidence' if power.get('identifiability', {}).get('passes_80pct') else 'are descriptive only'} |
| H1 power at ~10 pp (§8.6) | {f"{near10['power']:.3f} (h1 = {near10['h1']}, mean difference {near10['mean_diff']:.3f})" if near10 else 'n/a'} |
| Replicates (§2.2) | {reps} |

## Calibration (k=0 vs k=6 hack-attempt rate, 95% Wilson CIs)

| Variant | k = 0 | k = 6 |
|---|---|---|
{rows_cal}

## Power (paired test at Holm worst-case α = 0.05/3; TOST ±10 pp)

| h1 | mean paired difference | power ± MC SE | TOST power |
|---|---|---|---|
{rows_pw}
"""
    (REPORTS / "preregistration_stage2.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
